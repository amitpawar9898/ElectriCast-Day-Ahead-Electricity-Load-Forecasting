@app.get("/api/explain/residuals")
def get_explain_residuals(
    fold: str = Query(..., description="Fold id, e.g. 2017-07"),
    model: str = Query("xgboost", description="xgboost, sarima, or p50"),
):
    if model not in EXPLAIN_RESIDUAL_MODELS:
        return JSONResponse(
            status_code=400,
            content={"error": f"Unknown residual model '{model}'."},
        )
    if not BACKTEST_RESULTS:
        return JSONResponse(
            status_code=503,
            content={"error": "Backtest results not available. Run evaluate.py first."},
        )
    fold_meta = next(
        (item for item in BACKTEST_SUMMARY["folds"] if item["id"] == fold), None
    ) if BACKTEST_SUMMARY else None
    records = BACKTEST_RECORDS.get(fold)
    if fold_meta is None or not records:
        return JSONResponse(
            status_code=404,
            content={"error": f"No hourly backtest rows for fold '{fold}'."},
        )

    points = []
    residuals = []
    by_hour_sum = {hour: [0.0, 0.0, 0] for hour in range(24)}
    for record in records:
        actual = record.get("actual")
        predicted = record.get(model)
        if actual is None or predicted is None:
            continue
        residual = actual - predicted
        hour = int(record["time"][11:13])
        bucket = by_hour_sum[hour]
        bucket[0] += residual
        bucket[1] += abs(residual)
        bucket[2] += 1
        residuals.append(residual)
        points.append({
            "x": round(predicted, 2),
            "y": round(residual, 2),
        })

    by_hour = [{
        "hour": hour,
        "n": by_hour_sum[hour][2],
        "mean_residual_wh": round(by_hour_sum[hour][0] / by_hour_sum[hour][2], 2)
        if by_hour_sum[hour][2] else None,
        "mae_wh": round(by_hour_sum[hour][1] / by_hour_sum[hour][2], 2)
        if by_hour_sum[hour][2] else None,
    } for hour in range(24)]

    if residuals:
        summary = {
            "n": len(residuals),
            "mean_residual_wh": round(float(np.mean(residuals)), 2),
            "mae_wh": round(float(np.mean(np.abs(residuals))), 2),
            "rmse_wh": round(float(np.sqrt(np.mean(np.square(residuals)))), 2),
        }
        low, high = float(np.min(residuals)), float(np.max(residuals))
        if high <= low:
            histogram = [{
                "start": round(low, 2), "end": round(high, 2),
                "count": len(residuals),
            }]
        else:
            n_bins = 20
            width = (high - low) / n_bins
            counts = [0] * n_bins
            for value in residuals:
                index = min(int((value - low) / width), n_bins - 1)
                counts[index] += 1
            histogram = [{
                "start": round(low + index * width, 2),
                "end": round(low + (index + 1) * width, 2),
                "count": counts[index],
            } for index in range(n_bins)]
    else:
        summary = {"n": 0, "mean_residual_wh": None, "mae_wh": None, "rmse_wh": None}
        histogram = []

    return {
        "fold_id": fold,
        "fold_label": fold_meta["label"],
        "model": model,
        "model_label": EXPLAIN_RESIDUAL_MODELS[model],
        "summary": summary,
        "points": points,
        "by_hour": by_hour,
        "histogram": histogram,
    }


def _build_limitations():
    if not QUALITY or not BACKTEST_RESULTS:
        return None

    quality = QUALITY
    source = quality.get("source") or {}
    panel = quality.get("panel") or {}
    stable = quality.get("stable_panel") or {}
    target = quality.get("target") or {}
    inactive = quality.get("inactive") or {}
    results = BACKTEST_RESULTS
    weather = results.get("weather") or {}
    protocol = results.get("protocol") or {}

    fold_rows = []
    for fold in results.get("folds", []):
        model = (fold.get("models") or {}).get("sarima") or {}
        interval = (fold.get("intervals") or {}).get("xgboost_quantile") or {}
        conformal = (fold.get("intervals") or {}).get("conformal") or {}
        after_all = (conformal.get("after_all_days") or {}).get("coverage")
        after_calibrated = (conformal.get("after_calibrated_days") or {}).get("coverage")
        fit = (fold.get("model_fit") or {}).get("xgboost") or {}
        fold_rows.append({
            "id": fold["id"],
            "label": _fold_display(fold),
            "stress_test": bool(fold.get("stress_test")),
            "test_start": fold["test"]["start"],
            "test_end": fold["test"]["end"],
            "eval_hours": fold["test"]["eval_hours"],
            "eval_days": fold["test"]["eval_days"],
            "n_train_hours": fit.get("n_train"),
            "sarima_hours": model.get("n") if model.get("status") == "ok" else 0,
            "interval_coverage": interval.get("coverage"),
            "interval_n": interval.get("n"),
            "interval_after_coverage": after_all,
            "interval_after_calibrated_coverage": after_calibrated,
            "conformal_calibrated_days": conformal.get("n_days_calibrated"),
            "conformal_warmup_days": conformal.get("warmup_days"),
            "conformal_window_days": conformal.get("window_days"),
        })

    scoring_rows = [row for row in fold_rows if not row["stress_test"]]
    stress_rows = [row for row in fold_rows if row["stress_test"]]
    eval_hours = sum(row["eval_hours"] for row in fold_rows)
    eval_days = sum(row["eval_days"] for row in fold_rows)
    sarima_hours = sum(row["sarima_hours"] for row in fold_rows)
    coverage_rows = [row for row in fold_rows if row["interval_coverage"] is not None]
    after_rows = [
        row for row in fold_rows if row["interval_after_coverage"] is not None
    ]
    worst_after = min(after_rows, key=lambda row: row["interval_after_coverage"]) \
        if after_rows else None

